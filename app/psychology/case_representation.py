# 3. MULTI-DIMENSIONAL APPRAISAL HEURISTICS (Marked Explicitly as Hypotheses)
# =============================================================================

def _infer_appraisals(
    raw_text: str,
    facts: List[StatedFact],
    emotions: List[StatedEmotion],
    thoughts: List[StatedThoughtOrClaim],
) -> Tuple[List[InferredAppraisal], List[str]]:
    appraisals = []
    concerns = []
    lowered = raw_text.lower()

    # 1. Social Comparison & Peer Pacing
    if re.search(r"\b(friends|peers|colleagues|everyone)\b.*\b(placed|succeeding|doing better|invite|dinner)\b", lowered) or \
       re.search(r"\bkeep\s+up\s+with\s+(my\s+)?peers\b", lowered):
        evidence = [f.source_span for f in facts if f.category in ("actor", "event") and any(w in f.source_span.lower() for w in ["friends", "peers", "placed", "invite"])]
        if not evidence:
            m = re.search(r"\b(friends|peers|colleagues|everyone)[^.?!]*\b", lowered)
            evidence = [raw_text[m.start():m.end()].strip()] if m else ["Mention of peer pacing or social circle"]
        appraisals.append(InferredAppraisal(
            dimension="social_comparison",
            interpretation="Evaluation of personal pacing against observed peer progress or social inclusion.",
            confidence=0.85,
            evidence_spans=evidence,
            reasoning="User references external peers and compares personal status or involvement.",
        ))
        concerns.append("peer_comparison_and_pacing")

    # 2. Career Horizon / Future Transition
    if re.search(r"\b(career|graduation|graduate|job|placed|placement|future|promotion)\b", lowered):
        evidence = [f.source_span for f in facts if any(w in f.source_span.lower() for w in ["career", "graduation", "job", "placed", "promotion"])]
        if not evidence:
            m = re.search(r"\b(career|graduation|future)[^.?!]*\b", lowered)
            evidence = [raw_text[m.start():m.end()].strip()] if m else ["Career or future transition referenced"]
        appraisals.append(InferredAppraisal(
            dimension="career_horizon_uncertainty",
            interpretation="Anticipatory concern regarding professional transition and upcoming milestones.",
            confidence=0.88,
            evidence_spans=evidence,
            reasoning="User identifies a major impending transition into the workforce or professional role.",
        ))
        concerns.append("career_transition_uncertainty")

    # 3. Filial / Interpersonal Expectation Pressure
    if re.search(r"\b(disappoint\s+(my\s+)?(family|parents|mother|father|mom|dad))\b", lowered) or \
       re.search(r"\b(aging\s+mother|snapped\s+at\s+her)\b", lowered):
        evidence = [t.statement for t in thoughts if "disappoint" in t.statement.lower()] or \
                   [f.source_span for f in facts if any(w in f.source_span.lower() for w in ["family", "mother", "aging"])]
        appraisals.append(InferredAppraisal(
            dimension="evaluation_fear",
            interpretation="Concern regarding failing expectations of loved ones or feeling guilt over relational care.",
            confidence=0.82,
            evidence_spans=evidence,
            reasoning="User explicitly articulates fear of letting family down or guilt over caregiving interactions.",
        ))
        concerns.append("family_expectation_pressure")

    # 4. Perceived Self-Deficit
    if re.search(r"\b(haven'?t\s+done\s+enough|can'?t\s+be\s+productive|no\s+talent|awful\s+person|fraud|what'?s\s+wrong\s+with\s+me)\b", lowered):
        evidence = [t.statement for t in thoughts if any(w in t.statement.lower() for w in ["enough", "productive", "talent", "awful", "fraud", "wrong"])]
        appraisals.append(InferredAppraisal(
            dimension="perceived_deficit",
            interpretation="Internalized self-evaluation attributing difficulty to personal inadequacy or insufficient effort.",
            confidence=0.80,
            evidence_spans=evidence,
            reasoning="User verbalizes a feeling of falling short, being inadequate, or lacking necessary output.",
        ))
        concerns.append("self_deficit_evaluation")

    # 5. External Workplace Injustice / Powerlessness
    if re.search(r"\b(supervisor|boss|manager)\b.*\b(credit|stole|took|unfair)\b", lowered) or \
       re.search(r"\bfeel(ing)?\s+completely\s+powerless\b", lowered):
        evidence = [f.source_span for f in facts if "supervisor" in f.source_span.lower()] or ["Feeling powerless over workplace action"]
        appraisals.append(InferredAppraisal(
            dimension="systemic_injustice",
            interpretation="Experience of unacknowledged labor or unaddressed institutional unfairness.",
            confidence=0.90,
            evidence_spans=evidence,
            reasoning="User describes an external violation of professional fairness by authority figure.",
        ))
        concerns.append("workplace_injustice")

    # 6. Physical Illness / Bodily Limitation
    if re.search(r"\b(autoimmune|flare-up|sick|bed|chronic|illness|pain)\b", lowered):
        evidence = [f.source_span for f in facts if any(w in f.source_span.lower() for w in ["flare-up", "autoimmune", "bed"])]
        appraisals.append(InferredAppraisal(
            dimension="bodily_limitation",
            interpretation="Legitimate physiological depletion or health flare-up restricting physical capacity.",
            confidence=0.92,
            evidence_spans=evidence,
            reasoning="User explicitly identifies biological symptoms preventing physical activity.",
        ))
        concerns.append("bodily_illness_constraint")

    # 7. Executive Dysfunction / Behavioral Paralysis
    if re.search(r"\b(assignments\s+due|laundry|fridge|sitting\s+on\s+the\s+floor|unable\s+to\s+move|four\s+hours)\b", lowered):
        evidence = [f.source_span for f in facts if any(w in f.source_span.lower() for w in ["assignments", "laundry", "floor"])]
        appraisals.append(InferredAppraisal(
            dimension="executive_freeze",
            interpretation="Cognitive freeze / task accumulation resulting in behavioral immobility.",
            confidence=0.88,
            evidence_spans=evidence,
            reasoning="User describes competing tasks coupled with several hours of physical immobility.",
        ))
        concerns.append("executive_freeze")

    return appraisals, concerns


def _infer_uncertainty(raw_text: str, appraisals: List[InferredAppraisal]) -> UncertaintyProfile:
    lowered = raw_text.lower()
    dims = {a.dimension for a in appraisals}

    # Relational ambivalence
    if re.search(r"\b(don'?t\s+know\s+whether\s+to\s+try\s+harder\s+or\s+let\s+go|disconnected|dating|relationship)\b", lowered):
        return UncertaintyProfile(
            has_uncertainty=True,
            uncertainty_type="relational_ambivalence",
            is_inherently_unpredictable=True,
            preservation_required=True,
            evidence_spans=["I don't know whether to try harder or let go"],
        )

    # Climate / Macro existential
    if re.search(r"\b(planet\s+is\s+burning|hopeless\s+about\s+the\s+future|environmental\s+report)\b", lowered):
        return UncertaintyProfile(
            has_uncertainty=True,
            uncertainty_type="macro_existential",
            is_inherently_unpredictable=True,
            preservation_required=True,
            evidence_spans=["hopeless about the future", "planet is burning"],
        )

    # Future outcome / Career horizon
    if "career_horizon_uncertainty" in dims or re.search(r"\b(future|career|after graduation|what will happen)\b", lowered):
        return UncertaintyProfile(
            has_uncertainty=True,
            uncertainty_type="future_outcome",
            is_inherently_unpredictable=True,
            preservation_required=True,
            evidence_spans=["worried about my career after graduation"] if "career" in lowered else ["future"],
        )

    return UncertaintyProfile(has_uncertainty=False)


def _infer_controllability(facts: List[StatedFact], appraisals: List[InferredAppraisal]) -> ControllabilityAnalysis:
    dims = {a.dimension for a in appraisals}
    controllable = []
    uncontrollable = []

    if "career_horizon_uncertainty" in dims:
        controllable.append("Individual job applications, interview preparation, and personal daily pacing")
        uncontrollable.append("Macro hiring market timelines and specific employer decision schedules")

    if "social_comparison" in dims:
        uncontrollable.append("Other people's timelines, placements, and milestones")
        controllable.append("Focusing attention on personal growth and self-chosen criteria")

    if "evaluation_fear" in dims:
        uncontrollable.append("Family members' immediate emotional reactions or unspoken expectations")
        controllable.append("Communicating honestly about one's efforts and setting compassionate boundaries")

    if "systemic_injustice" in dims:
        uncontrollable.append("Supervisor's past behavior during the meeting")
        controllable.append("Documenting work, speaking with HR/mentors, or establishing project boundaries")

    if "bodily_limitation" in dims:
        uncontrollable.append("Biological flare-up and involuntary physical exhaustion")
        controllable.append("Permitting restful recovery and hydration without self-blame")

    if "executive_freeze" in dims:
        controllable.append("Selecting a single 2-minute entry task (e.g. drinking water, clearing one item)")
        uncontrollable.append("Completing all assignments and household chores all at once")

    return ControllabilityAnalysis(
        potentially_controllable=controllable,
        potentially_uncontrollable=uncontrollable,
        confidence=0.75 if (controllable or uncontrollable) else 0.3,
    )


def _infer_support_needs(
    appraisals: List[InferredAppraisal],
    uncertainty: UncertaintyProfile,
) -> SupportNeedsHypothesis:
    dims = {a.dimension for a in appraisals}
    possible_needs = []
    contraindications = []

    if "bodily_limitation" in dims:
        possible_needs.append("empathetic_validation")
        possible_needs.append("permission_to_rest")
        contraindications.append("do_not_frame_physical_illness_as_cognitive_distortion")
        contraindications.append("do_not_demand_productivity_steps")

    if "systemic_injustice" in dims:
        possible_needs.append("validation_of_injustice")
        possible_needs.append("boundary_and_objective_options")
        contraindications.append("do_not_gaslight_or_reframe_supervisor_behavior")

    if uncertainty.uncertainty_type == "relational_ambivalence":
        possible_needs.append("holding_space_for_ambivalence")
        possible_needs.append("reflective_clarification")
        contraindications.append("do_not_force_premature_decision_or_false_certainty")

    if "social_comparison" in dims and "career_horizon_uncertainty" in dims:
        possible_needs.append("values_clarification_and_pacing_differentiation")
        possible_needs.append("decoupling_self_worth_from_peer_timeline")
        contraindications.append("do_not_dismiss_family_concern_as_irrational")

    if "executive_freeze" in dims:
        possible_needs.append("somatic_grounding_and_micro_step")
        contraindications.append("do_not_overwhelm_with_multi_step_planning")

    return SupportNeedsHypothesis(
        possible_needs=possible_needs or ["open_reflective_exploration"],
        contraindications=contraindications,
    )


def _identify_unknowns(
    raw_text: str,
    facts: List[StatedFact],
    emotions: List[StatedEmotion],
    thoughts: List[StatedThoughtOrClaim],
    appraisals: List[InferredAppraisal],
) -> UnknownOrUnstatedInfo:
    dims = {a.dimension for a in appraisals}
    missing = []

    if "career_horizon_uncertainty" in dims:
        missing.append("Specific career field, target roles, or active applications")
        missing.append("What 'doing enough' specifically means to the user")

    if "evaluation_fear" in dims:
        missing.append("Family's actual stated expectations vs. internal anticipated dread")

    if "social_comparison" in dims:
        missing.append("User's own personal criteria for success independent of friends")

    if "bodily_limitation" in dims:
        missing.append("Current medical guidance or accommodation options")

    if "systemic_injustice" in dims:
        missing.append("Workplace reporting structures or written documentation of project authorship")

    if not facts:
        missing.append("Concrete situational trigger or context")

    missing.append("User's preferred support modality (listening vs. planning vs. perspective)")

    return UnknownOrUnstatedInfo(missing_aspects=missing)



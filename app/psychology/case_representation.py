_ACTOR_KEYWORDS = {
    "friends": "actor", "friend": "actor", "family": "actor", "parents": "actor",
    "mother": "actor", "father": "actor", "mom": "actor", "dad": "actor",
    "supervisor": "actor", "boss": "actor", "colleague": "actor", "colleagues": "actor",
    "coworker": "actor", "peers": "actor", "peer": "actor", "partner": "actor",
    "boyfriend": "actor", "girlfriend": "actor", "team": "actor", "manager": "actor",
}

_MILESTONE_KEYWORDS = {
    "graduation": "milestone", "career": "domain", "job": "domain", "placement": "milestone",
    "placed": "milestone", "promotion": "milestone", "promoted": "milestone",
    "dating": "relationship", "relationship": "relationship", "partner": "relationship",
    "report": "document", "environmental report": "document", "planet": "macro_context",
    "interview": "event", "exam": "event", "test": "event", "presentation": "event",
    "meeting": "event", "assignments": "obligation", "manuscript": "creative_work",
    "project": "obligation", "dinner party": "event", "flare-up": "condition",
    "autoimmune": "condition", "laundry": "activity", "fridge": "condition",
}

_EMOTION_LEXICON = {
    "worried": ("negative", "worry/anxiety"),
    "worry": ("negative", "worry/anxiety"),
    "worries": ("negative", "worry/anxiety"),
    "scared": ("negative", "fear"),
    "fear": ("negative", "fear"),
    "afraid": ("negative", "fear"),
    "happy": ("positive", "joy/sympathy"),
    "glad": ("positive", "joy/sympathy"),
    "guilty": ("negative", "guilt"),
    "guilt": ("negative", "guilt"),
    "furious": ("negative", "anger"),
    "angry": ("negative", "anger"),
    "hopeless": ("negative", "despair"),
    "overwhelmed": ("negative", "overwhelm"),
    "disconnected": ("negative", "alienation"),
    "crying": ("negative", "acute_sadness"),
    "numb": ("negative", "blunting"),
    "anxious": ("negative", "anxiety"),
    "stressed": ("negative", "stress"),
    "confused": ("negative", "confusion"),
    "sad": ("negative", "sadness"),
}


def _extract_stated_facts(doc, raw_text: str) -> List[StatedFact]:
    facts = []
    lowered = raw_text.lower()

    # 1. Actors from keywords and noun chunks
    for token in doc:
        w = token.lemma_.lower()
        if w in _ACTOR_KEYWORDS:
            span = token.text
            start = token.idx
            end = start + len(span)
            facts.append(StatedFact(
                text=span,
                category=_ACTOR_KEYWORDS[w],
                source_span=span,
                start_char=start,
                end_char=end,
            ))

    # 2. Key domain, milestone, and condition entities
    for chunk in doc.noun_chunks:
        chunk_text = chunk.text.strip()
        chunk_lower = chunk_text.lower()
        for kw, cat in _MILESTONE_KEYWORDS.items():
            if re.search(rf"\b{re.escape(kw)}\b", chunk_lower):
                start = chunk.start_char
                end = chunk.end_char
                facts.append(StatedFact(
                    text=chunk_text,
                    category=cat,
                    source_span=chunk_text,
                    start_char=start,
                    end_char=end,
                ))
                break

    event_patterns = [
        (r"\bfriends\s+(are\s+)?getting\s+placed\b", "event", "friends getting placed"),
        (r"\bdisappoint\s+(my\s+)?family\b", "stated_concern", "concern: disappointing family"),
        (r"\bautoimmune\s+flare-up\s+returned\b", "condition", "autoimmune flare-up returned"),
        (r"\bgave\s+credit\s+for\s+my\s+.*\s+project\b", "event", "supervisor gave credit to colleague"),
        (r"\bpromoted\s+to\s+lead\b", "milestone", "promoted to lead"),
        (r"\btaking\s+care\s+of\s+my\s+aging\s+mother\b", "event", "caregiving for aging mother"),
        (r"\bsnapped\s+at\s+her\b", "event", "snapped at mother"),
        (r"\bmanuscript\s+was\s+rejected\b", "event", "manuscript rejected"),
        (r"\bdinner\s+party\s+.*\s+didn'?t\s+invite\s+me\b", "event", "friends dinner party without invitation"),
        (r"\bsitting\s+on\s+the\s+floor\b", "behavioral_state", "sitting on floor"),
        (r"\bcan barely get out of bed\b", "physical_state", "unable to get out of bed"),
        (r"\b(drained\s+all\s+my\s+energy|completely\s+drained|exhausted)\b", "physical_state", "physical exhaustion"),
        (r"\b(paralyzed|unable\s+to\s+move)\b", "behavioral_state", "behavioral immobility"),
    ]
    for pattern, cat, label in event_patterns:
        m = re.search(pattern, lowered)
        if m:
            span = raw_text[m.start():m.end()]
            facts.append(StatedFact(
                text=label,
                category=cat,
                source_span=span,
                start_char=m.start(),
                end_char=m.end(),
            ))

    # Deduplicate by start/end char
    seen = set()
    deduped = []
    for f in facts:
        key = (f.start_char, f.end_char)
        if key not in seen:
            seen.add(key)
            deduped.append(f)
    return deduped


def _extract_stated_emotions(doc, raw_text: str) -> List[StatedEmotion]:
    emotions = []
    lowered = raw_text.lower()

    for token in doc:
        lemma = token.lemma_.lower()
        word = token.text.lower()
        key = word if word in _EMOTION_LEXICON else (lemma if lemma in _EMOTION_LEXICON else None)

        if key:
            valence, label = _EMOTION_LEXICON[key]
            start = token.idx
            end = start + len(token.text)
            target = None

            # Look for syntactic target (e.g. "worried about career", "scared that...")
            for child in token.children:
                if child.dep_ in ("prep", "ccomp", "dobj"):
                    target_span = raw_text[child.idx:child.idx + len(child.subtree_text) if hasattr(child, "subtree_text") else child.idx + 25]
                    target = target_span.strip()
                    break

            emotions.append(StatedEmotion(
                emotion_word=token.text,
                valence=valence,
                target=target,
                source_span=token.sent.text.strip() if token.sent else token.text,
                start_char=start,
                end_char=end,
            ))

    # Deduplicate
    seen = set()
    deduped = []
    for e in emotions:
        key = (e.start_char, e.end_char)
        if key not in seen:
            seen.add(key)
            deduped.append(e)
    return deduped


def _extract_stated_thoughts(doc, raw_text: str) -> List[StatedThoughtOrClaim]:
    thoughts = []
    lowered = raw_text.lower()

    thought_patterns = [
        r"\bi\s+haven'?t\s+done\s+enough\b",
        r"\bi'?ll\s+disappoint\s+(my\s+)?family\b",
        r"\bi\s+can'?t\s+be\s+productive\b",
        r"\bcan barely get out of bed\b",
        r"\bi\s+feel\s+completely\s+powerless\b",
        r"\bi\s+don'?t\s+know\s+whether\s+to\s+try\s+harder\s+or\s+let\s+go\b",
        r"\bi\s+feel\s+like\s+an?\s+(absolute\s+)?fraud\b",
        r"\bthey\s+will\s+realize\s+i\s+have\s+no\s+idea\b",
        r"\bi\s+feel\s+like\s+an\s+awful\s+person\b",
        r"\bwhat'?s\s+the\s+point\s+of\s+planning\b",
        r"\bplanet\s+is\s+burning\b",
        r"\bi\s+simply\s+have\s+no\s+talent\b",
        r"\bwasted\s+years\s+of\s+my\s+life\b",
        r"\bwondering\s+what'?s\s+wrong\s+with\s+me\b",
        r"\bunable\s+to\s+move\b",
    ]

    for pat in thought_patterns:
        m = re.search(pat, lowered)
        if m:
            span = raw_text[m.start():m.end()]
            thoughts.append(StatedThoughtOrClaim(
                statement=span,
                source_span=span,
                start_char=m.start(),
                end_char=m.end(),
            ))

    return thoughts



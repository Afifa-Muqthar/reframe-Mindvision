# 4. PRIMARY EXTRACTION PIPELINE
# =============================================================================

def extract_case_representation(
    text: str,
    emotion_scores: Optional[Dict[str, float]] = None,
    core_emotion: Optional[str] = None,
) -> CaseRepresentation:
    """
    Main extraction entry point for Stage 1.
    Transforms raw user text and optional emotion predictions into a rich,
    multi-dimensional CaseRepresentation without dropping facts or substituting generic fallbacks.
    """
    cleaned = (text or "").strip()
    if not cleaned:
        return CaseRepresentation(
            raw_text="",
            is_partial=True,
            descriptive_summary="Empty input received.",
            unknowns=UnknownOrUnstatedInfo(missing_aspects=["All context and information"]),
        )

    nlp = get_spacy_nlp()
    doc = nlp(cleaned)

    # 1. Stated facts, emotions, and thoughts
    stated_facts = _extract_stated_facts(doc, cleaned)
    stated_emotions = _extract_stated_emotions(doc, cleaned)
    stated_thoughts = _extract_stated_thoughts(doc, cleaned)

    # 2. Predicted emotions from model (kept strictly separate from stated emotions)
    predicted_emotions = []
    if emotion_scores:
        sorted_scores = sorted(emotion_scores.items(), key=lambda x: x[1], reverse=True)
        for label, score in sorted_scores[:3]:
            predicted_emotions.append(PredictedEmotion(
                label=label,
                score=float(score),
                source_model="roberta-goemotions-onnx",
            ))
    elif core_emotion:
        predicted_emotions.append(PredictedEmotion(
            label=core_emotion,
            score=1.0,
            source_model="inferred_core",
        ))

    # 3. Multi-dimensional appraisal hypotheses
    inferred_appraisals, interacting_concerns = _infer_appraisals(
        cleaned, stated_facts, stated_emotions, stated_thoughts
    )

    # 4. Uncertainty profile
    uncertainty = _infer_uncertainty(cleaned, inferred_appraisals)

    # 5. Controllability analysis
    controllability = _infer_controllability(stated_facts, inferred_appraisals)

    # 6. Support needs hypotheses
    support_needs = _infer_support_needs(inferred_appraisals, uncertainty)

    # 7. Explicit unknowns
    unknowns = _identify_unknowns(cleaned, stated_facts, stated_emotions, stated_thoughts, inferred_appraisals)

    # 8. Build traceability map (Linking each inferred dimension to exact user substrings)
    traceability_map = {}
    for a in inferred_appraisals:
        traceability_map[f"appraisal_{a.dimension}"] = a.evidence_spans
    if uncertainty.evidence_spans:
        traceability_map["uncertainty"] = uncertainty.evidence_spans
    for f in stated_facts:
        traceability_map[f"fact_{f.category}_{f.text}"] = [f.source_span]
    for e in stated_emotions:
        traceability_map[f"emotion_{e.emotion_word}"] = [e.source_span]

    # 9. Descriptive summary (Grounding in stated facts, NEVER generic general_stress boilerplate)
    fact_texts = [f.text for f in stated_facts if f.category in ("actor", "milestone", "condition")]
    concerns_summary = ", ".join(interacting_concerns) if interacting_concerns else "emerging personal challenge"
    emotions_summary = ", ".join(f"{e.emotion_word}" for e in stated_emotions) if stated_emotions else "unspecified emotional tension"
    
    descriptive_summary = (
        f"Context involves {', '.join(fact_texts[:3]) if fact_texts else 'personal reflection'}. "
        f"Stated emotions: [{emotions_summary}]. "
        f"Active dimensions: [{concerns_summary}]."
    )

    is_partial = len(stated_facts) == 0 and len(stated_emotions) <= 1 and len(stated_thoughts) == 0 and not uncertainty.has_uncertainty

    return CaseRepresentation(
        raw_text=cleaned,
        stated_facts=stated_facts,
        stated_emotions=stated_emotions,
        predicted_emotions=predicted_emotions,
        stated_thoughts=stated_thoughts,
        interacting_concerns=interacting_concerns,
        inferred_appraisals=inferred_appraisals,
        uncertainty=uncertainty,
        controllability=controllability,
        support_needs=support_needs,
        unknowns=unknowns,
        traceability_map=traceability_map,
        is_partial=is_partial,
        descriptive_summary=descriptive_summary,
    )

"""
Multi-Dimensional Case Representation Engine for MindVision.

Stage 1 Architecture:
Preserves user-stated facts, multiple interacting concerns, emotions, appraisals,
uncertainty, controllability, and support needs as separate, traceable fields.

Core Principles:
1. Strict separation of Stated Information (explicit) from Inferred Information (model hypotheses).
2. Explicit vs. Predicted emotions (user's words vs classifier scores).
3. Zero invention of visual details or premature psychological decisions (no forced CBT, no generic boilerplate).
4. Explicit tracking of Unknowns / Unstated information.
5. Full semantic traceability back to source text spans.
6. Robust handling of compound, ambiguous, misspelled, and partial inputs.
"""

import re
from dataclasses import dataclass, field, asdict
from typing import Dict, List, Any, Optional, Tuple

import spacy

_nlp = None


def get_spacy_nlp():
    global _nlp
    if _nlp is None:
        try:
            _nlp = spacy.load("en_core_web_sm")
        except Exception:
            _nlp = spacy.blank("en")
            if "sentencizer" not in _nlp.pipe_names:
                _nlp.add_pipe("sentencizer")
    return _nlp


# =============================================================================
# 1. DATA CONTRACTS (Typed, Validated, Explicit Separation)
# =============================================================================

@dataclass
class StatedFact:
    """A concrete entity, actor, event, or condition explicitly mentioned by the user."""
    text: str
    category: str          # "actor", "milestone", "condition", "activity", "obligation", "event"
    source_span: str       # Exact verbatim substring from raw text
    start_char: int
    end_char: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class StatedEmotion:
    """An emotional state explicitly verbalized by the user."""
    emotion_word: str      # Exact verbatim word or lemma (e.g. "scared", "happy", "worried")
    valence: str           # "negative", "positive", "ambivalent"
    target: Optional[str]  # What the emotion is directed at (if syntactically attached)
    source_span: str       # Verbatim clause or phrase
    start_char: int
    end_char: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class PredictedEmotion:
    """An emotion prediction generated by an external classifier (e.g. RoBERTa ONNX)."""
    label: str
    score: float           # 0.0 to 1.0
    source_model: str = "roberta-goemotions-onnx"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class StatedThoughtOrClaim:
    """A verbatim thought, belief, evaluation, or question stated by the user."""
    statement: str         # e.g. "I haven't done enough", "I'll disappoint my family"
    source_span: str       # Exact verbatim substring
    start_char: int
    end_char: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class InferredAppraisal:
    """A model-inferred psychological appraisal, marked explicitly as a hypothesis."""
    dimension: str         # "social_comparison", "career_horizon_uncertainty", "evaluation_fear", "perceived_deficit", "locus_of_control", "temporal_focus"
    interpretation: str    # Human-readable explanation
    confidence: float      # 0.0 to 1.0
    status: str = "hypothesized"  # Always marked as hypothesis, never established fact
    evidence_spans: List[str] = field(default_factory=list)
    reasoning: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class UncertaintyProfile:
    """Assessment of genuine uncertainty vs. predictable facts."""
    has_uncertainty: bool
    uncertainty_type: Optional[str] = None  # "future_outcome", "relational_ambivalence", "decision_doubt", "unclear"
    is_inherently_unpredictable: bool = False
    preservation_required: bool = False     # If True, system must hold space, not force false reassurance
    evidence_spans: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ControllabilityAnalysis:
    """Delineation of potentially controllable vs. uncontrollable factors as hypotheses."""
    potentially_controllable: List[str] = field(default_factory=list)
    potentially_uncontrollable: List[str] = field(default_factory=list)
    confidence: float = 0.5
    status: str = "inferred_hypothesis"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SupportNeedsHypothesis:
    """Potential support modalities based on the case, without imposing CBT."""
    possible_needs: List[str] = field(default_factory=list)  # e.g. ["validation", "perspective_differentiation", "practical_structuring", "holding_space"]
    contraindications: List[str] = field(default_factory=list) # e.g. ["do_not_minimize_external_barrier", "do_not_force_premature_action"]
    status: str = "uncertain_hypothesis"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class UnknownOrUnstatedInfo:
    """Explicitly tracks what the user has NOT provided to prevent hallucinations."""
    missing_aspects: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class CaseRepresentation:
    """
    Comprehensive, multi-dimensional context representation.
    Preserves all user-stated information and isolates inferences with full traceability.
    """
    raw_text: str
    stated_facts: List[StatedFact] = field(default_factory=list)
    stated_emotions: List[StatedEmotion] = field(default_factory=list)
    predicted_emotions: List[PredictedEmotion] = field(default_factory=list)
    stated_thoughts: List[StatedThoughtOrClaim] = field(default_factory=list)
    interacting_concerns: List[str] = field(default_factory=list)
    inferred_appraisals: List[InferredAppraisal] = field(default_factory=list)
    uncertainty: UncertaintyProfile = field(default_factory=lambda: UncertaintyProfile(has_uncertainty=False))
    controllability: ControllabilityAnalysis = field(default_factory=ControllabilityAnalysis)
    support_needs: SupportNeedsHypothesis = field(default_factory=SupportNeedsHypothesis)
    unknowns: UnknownOrUnstatedInfo = field(default_factory=UnknownOrUnstatedInfo)
    traceability_map: Dict[str, List[str]] = field(default_factory=dict)
    is_partial: bool = False
    descriptive_summary: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


